"""Data audit. Run: python -m src.audit -> outputs/diagnostics/audit.md (+ 3 figures)."""
import numpy as np
import pandas as pd
from scipy.stats import spearmanr, kurtosis, skew
from src.data import load, load_raw, numeric_columns, ROOT, RETURNS

OUT = ROOT / "outputs" / "diagnostics"
INK, MUTED, BLUE = "#1f2933", "#7b8794", "#2f6fb0"


def _style(ax, title, xl, yl):
    ax.set_title(title, loc="left", fontsize=10, color=INK)
    ax.set_xlabel(xl, fontsize=9, color=MUTED)
    ax.set_ylabel(yl, fontsize=9, color=MUTED)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    for s in ("left", "bottom"):
        ax.spines[s].set_color("#cbd2d9")
    ax.tick_params(colors=MUTED, labelsize=8)
    ax.grid(True, color="#e4e7eb", linewidth=0.6)
    ax.set_axisbelow(True)


def main():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    OUT.mkdir(parents=True, exist_ok=True)
    rtr, rte = load_raw()
    tr, te, days = load()
    num = list(days.columns)
    L = []
    P = L.append
    P("# Data audit (generated by `python -m src.audit`)\n")
    P("## 1. Panel structure\n")
    P(f"- train {rtr.shape[0]} rows, test {rte.shape[0]} rows; {days.shape[0]} distinct days; {len(num)} independent numeric variables")
    for a, b in [("FR_DE_EXCHANGE", "DE_FR_EXCHANGE"), ("DE_NET_IMPORT", "DE_NET_EXPORT"), ("FR_NET_IMPORT", "FR_NET_EXPORT")]:
        P(f"- `{a}` = -`{b}` exactly (max abs sum {np.nanmax(np.abs(rtr[a] + rtr[b])):.1e}): dropped")
    both = pd.concat([rtr.drop(columns='TARGET'), rte])
    g = both.groupby("DAY_ID").COUNTRY.agg(lambda s: "+".join(sorted(s)))
    P(f"- rows per day: {g.value_counts().to_dict()} (every day has an FR row; DE is missing on some days)")
    two = both.groupby("DAY_ID").filter(lambda d: len(d) == 2).sort_values(["DAY_ID", "COUNTRY"])
    diff = np.nanmax(np.abs(two[two.COUNTRY == "DE"][num].values - two[two.COUNTRY == "FR"][num].values))
    P(f"- explanatory variables of the FR and DE rows of a day are identical (max difference {diff:.1e})")
    P(f"- no day is shared between train and test: {len(set(rtr.DAY_ID) & set(rte.DAY_ID))} common DAY_ID")

    P("\n## 2. Chronology: `ID` is ordered in time, `DAY_ID` is not\n")
    P(f"- ID ranges: DE {both[both.COUNTRY == 'DE'].ID.min()}-{both[both.COUNTRY == 'DE'].ID.max()}, FR {both[both.COUNTRY == 'FR'].ID.min()}-{both[both.COUNTRY == 'FR'].ID.max()}")
    by_day = both.drop_duplicates("DAY_ID").set_index("DAY_ID").sort_index()
    rows = []
    for c in ["FR_NUCLEAR", "FR_CONSUMPTION", "DE_SOLAR", "DE_TEMP", "DE_WINDPOW", "DE_RESIDUAL_LOAD", "GAS_RET"]:
        rows.append({"variable": c, "lag-1 autocorr, DAY_ID order": by_day[c].autocorr(1), "lag-1 autocorr, ID order": days[c].autocorr(1)})
    ac = pd.DataFrame(rows).set_index("variable").round(3)
    P(ac.to_markdown())
    de = both[both.COUNTRY == "DE"].sort_values("ID")
    tmap = tr.set_index("DAY_ID").t.to_dict() | te.set_index("DAY_ID").t.to_dict()
    P(f"\n- the DE block sorted by ID visits the days in the same order as the FR block: {bool((np.diff([tmap[d] for d in de.DAY_ID]) > 0).all())}")
    P("- so t = rank of the FR row's ID is a time axis for all 1,216 days (`src/data.py`).")
    P("- no weekly cycle: t mod 5 or 7 explains under 1% of the variance of consumption changes, so t is ordinal, not a calendar.")
    is_test = np.isin(days.index, te.t.unique())
    runs = int((np.diff(is_test.astype(int)) != 0).sum()) + 1
    P(f"- test days are interleaved with train days at random: {runs} train/test alternations along time, {int(2 * is_test.sum() * (~is_test).sum() / len(is_test)) + 1} expected under random mixing; test share per time decile {np.round([is_test[i].mean() for i in np.array_split(np.arange(len(is_test)), 10)], 2).tolist()}")
    tde = np.sort(np.unique(np.concatenate([tr[tr.COUNTRY == 'DE'].t, te[te.COUNTRY == 'DE'].t])))
    P(f"- DE rows exist for every day from t = {tde.min()} onwards ({len(tde)} days, no gap: {bool(len(tde) == 1216 - tde.min())}); before that the panel is FR only")

    P("\n## 3. Missing values (% of days)\n")
    na = (days.isna().mean() * 100).round(1)
    P(na[na > 0].to_frame("missing %").to_markdown())
    P(f"\n- export/exchange variables are missing only in the FR-only period (t < {tde.min()}): {bool(days.loc[days.index >= tde.min(), ['DE_NET_EXPORT', 'FR_NET_EXPORT', 'DE_FR_EXCHANGE']].isna().sum().sum() == 0)}")

    P("\n## 4. Target\n")
    Y = tr.pivot(index="t", columns="COUNTRY", values="TARGET").reindex(days.index)
    rows = []
    for c in ("FR", "DE"):
        y = Y[c].dropna()
        rows.append({"country": c, "n": len(y), "mean": y.mean(), "median": y.median(), "std": y.std(), "skew": skew(y), "excess kurtosis": kurtosis(y),
                     "q01": y.quantile(.01), "q99": y.quantile(.99), "autocorr lag1": Y[c].autocorr(1), "autocorr lag2": Y[c].autocorr(2),
                     "|y| autocorr lag1": Y[c].abs().autocorr(1)})
    P(pd.DataFrame(rows).set_index("country").round(3).T.to_markdown())
    P(f"\n- same-day FR/DE target Spearman: {spearmanr(Y.FR, Y.DE, nan_policy='omit').correlation:.3f}")

    P("\n## 5. What explains the target: level today vs change since yesterday (Spearman)\n")
    rows = []
    for f in num:
        x = days[f]
        r = {"variable": f}
        for c in ("DE", "FR"):
            r[f"{c} level"] = spearmanr(x, Y[c], nan_policy="omit").correlation
            r[f"{c} change"] = spearmanr(x - x.shift(1), Y[c], nan_policy="omit").correlation
            r[f"{c} trend3"] = spearmanr(sum(x.shift(-k) for k in (1, 2, 3)) / 3 - sum(x.shift(k) for k in (1, 2, 3)) / 3, Y[c], nan_policy="omit").correlation
        r["FR lag-1 level"] = spearmanr(x.shift(1), Y.FR, nan_policy="omit").correlation
        rows.append(r)
    T = pd.DataFrame(rows).set_index("variable").round(3)
    P(T.reindex(T.abs().max(axis=1).sort_values(ascending=False).index).to_markdown())
    P("\n'trend3' = mean of the 3 following days minus mean of the 3 previous days.")

    P("\n## 6. Collinearity (|Pearson| > 0.8 between day-level variables)\n")
    cm = days.corr()
    for i, a in enumerate(num):
        for b in num[i + 1:]:
            if abs(cm.loc[a, b]) > 0.8:
                P(f"- {a} / {b}: {cm.loc[a, b]:.2f}")

    # figures
    fig, ax = plt.subplots(1, 2, figsize=(9, 3.6))
    dx = days.DE_RESIDUAL_LOAD - days.DE_RESIDUAL_LOAD.shift(1)
    for a, x, xl, ttl in ((ax[0], days.DE_RESIDUAL_LOAD, "DE residual load, level", "Level today"), (ax[1], dx, "DE residual load, change since previous day", "Change since yesterday")):
        m = Y.DE.notna() & x.notna()
        a.scatter(x[m], Y.DE[m].clip(-3, 3), s=9, color=BLUE, alpha=0.55, linewidths=0)
        _style(a, f"{ttl}: Spearman {spearmanr(x[m], Y.DE[m]).correlation:.2f}", xl, "DE target (clipped at ±3)")
    fig.tight_layout(); fig.savefig(OUT / "fig_de_level_vs_change.png", dpi=140); plt.close(fig)

    fig, ax = plt.subplots(figsize=(6.5, 3.4))
    lags = np.arange(1, 11)
    ax.plot(lags, [days.FR_CONSUMPTION.autocorr(l) for l in lags], color=BLUE, linewidth=2, marker="o", markersize=5)
    ax.plot(lags, [by_day.FR_CONSUMPTION.autocorr(l) for l in lags], color=MUTED, linewidth=2, marker="o", markersize=5)
    ax.annotate("rows ordered by ID", (lags[-1], days.FR_CONSUMPTION.autocorr(10)), xytext=(-4, 8), textcoords="offset points", ha="right", fontsize=9, color=INK)
    ax.annotate("rows ordered by DAY_ID", (lags[-1], by_day.FR_CONSUMPTION.autocorr(10)), xytext=(-4, 8), textcoords="offset points", ha="right", fontsize=9, color=INK)
    _style(ax, "Autocorrelation of FR consumption", "lag (rows)", "autocorrelation")
    fig.tight_layout(); fig.savefig(OUT / "fig_autocorr_id_vs_dayid.png", dpi=140); plt.close(fig)

    fig, ax = plt.subplots(figsize=(6.5, 3.4))
    ks = list(range(-5, 6))
    x = days.FR_CONSUMPTION
    ax.bar(ks, [spearmanr(x.shift(-k), Y.FR, nan_policy="omit").correlation for k in ks], color=BLUE, width=0.6)
    ax.axhline(0, color="#9aa5b1", linewidth=0.8)
    _style(ax, "FR target vs FR consumption on day t+k: past days weigh negatively", "k (days relative to the target day)", "Spearman")
    fig.tight_layout(); fig.savefig(OUT / "fig_fr_lead_lag_profile.png", dpi=140); plt.close(fig)

    P("\n## Figures\n\n- `fig_autocorr_id_vs_dayid.png`\n- `fig_de_level_vs_change.png`\n- `fig_fr_lead_lag_profile.png`")
    (OUT / "audit.md").write_text("\n".join(L))
    print("\n".join(L[:60]))


if __name__ == "__main__":
    main()
